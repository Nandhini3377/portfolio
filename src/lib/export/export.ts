// Export a portfolio as (a) a static site or (b) a SvelteKit project.
// The SvelteKit export ships the exact renderer source used for the live preview,
// so both outputs look identical.

import { strToU8, zipSync } from 'fflate';
import type { Portfolio } from '#lib/portfolio/types.ts';
import { renderPortfolio } from '#lib/render/index.ts';
import { slug } from '#lib/render/util.ts';

export type ExportFiles = Record<string, string>;

const rendererSource = import.meta.glob('../render/**/*.ts', { query: '?raw', import: 'default', eager: true }) as Record<string, string>;
const typesSource = import.meta.glob('../portfolio/types.ts', { query: '?raw', import: 'default', eager: true }) as Record<string, string>;

export function staticSiteFiles(p: Portfolio): ExportFiles {
	return {
		'index.html': renderPortfolio(p),
		'README.md': `# ${p.profile.name} — portfolio\n\nA static site. Open \`index.html\` in a browser, or deploy this folder to any static host (Vercel, GitHub Pages, Netlify).\n`
	};
}

export function svelteKitFiles(p: Portfolio): ExportFiles {
	const name = slug(p.profile.name) + '-portfolio';
	const files: ExportFiles = {
		'package.json': JSON.stringify(
			{
				name,
				private: true,
				version: '1.0.0',
				type: 'module',
				scripts: { dev: 'vite dev', build: 'vite build', preview: 'vite preview' },
				devDependencies: {
					'@sveltejs/adapter-static': '^4.0.0',
					'@sveltejs/kit': '^3.1.0',
					'@sveltejs/vite-plugin-svelte': '^7.2.0',
					svelte: '^5.57.0',
					typescript: '^6.0.0',
					vite: '^8.3.0'
				}
			},
			null,
			2
		),
		'vite.config.ts': `import adapter from '@sveltejs/adapter-static';
import { sveltekit } from '@sveltejs/kit/vite';
import { defineConfig } from 'vite';

export default defineConfig({
	plugins: [sveltekit({ adapter: adapter() })]
});
`,
		'tsconfig.json': JSON.stringify({ extends: '$app/tsconfig', compilerOptions: { strict: true }, include: ['src', '*'] }, null, 2),
		'.gitignore': 'node_modules\n.svelte-kit\nbuild\n.vercel\n',
		'src/app.html': `<!doctype html>
<html lang="en">
	<head>
		<meta charset="utf-8" />
		<meta name="viewport" content="width=device-width, initial-scale=1" />
		%sveltekit.head%
	</head>
	<body>
		<div style="display: contents">%sveltekit.body%</div>
	</body>
</html>
`,
		'src/routes/+layout.ts': 'export const prerender = true;\n',
		'src/routes/+page.svelte': `<script lang="ts">
	import data from '../lib/portfolio.json';
	import type { Portfolio } from '../lib/portfolio/types';
	import { renderBody, renderStyles } from '../lib/render';

	// Edit src/lib/portfolio.json to change content; the renderer escapes all text.
	const p = data as Portfolio;
	const title = p.profile.headline ? \`\${p.profile.name} — \${p.profile.headline}\` : p.profile.name;
</script>

<svelte:head>
	<title>{title}</title>
	<meta name="description" content={p.profile.headline} />
	{@html \`<style>\${renderStyles(p)}</style>\`}
</svelte:head>

{@html renderBody(p)}
`,
		'src/lib/portfolio.json': JSON.stringify(p, null, 2),
		'README.md': `# ${p.profile.name} — portfolio

A SvelteKit project generated by Offline AI Portfolio Builder.

\`\`\`sh
npm install
npm run dev     # local preview
npm run build   # static output in build/
\`\`\`

Content lives in \`src/lib/portfolio.json\`. Deploys to Vercel with zero configuration.
`
	};
	for (const [path, source] of Object.entries(rendererSource)) files[`src/lib/${path.replace('../', '')}`] = source;
	for (const [path, source] of Object.entries(typesSource)) files[`src/lib/${path.replace('../', '')}`] = source;
	return files;
}

export function zipFiles(files: ExportFiles, folder: string): Uint8Array {
	const entries: Record<string, Uint8Array> = {};
	for (const [path, content] of Object.entries(files)) entries[`${folder}/${path}`] = strToU8(content);
	return zipSync(entries, { level: 6 });
}

export function download(data: Uint8Array | string, filename: string, type: string) {
	const blob = new Blob([data as BlobPart], { type });
	const url = URL.createObjectURL(blob);
	const a = Object.assign(document.createElement('a'), { href: url, download: filename });
	document.body.append(a);
	a.click();
	a.remove();
	setTimeout(() => URL.revokeObjectURL(url), 1000);
}

export function exportStatic(p: Portfolio) {
	const folder = slug(p.profile.name) + '-portfolio';
	download(zipFiles(staticSiteFiles(p), folder), `${folder}-static.zip`, 'application/zip');
}

export function exportSvelteKit(p: Portfolio) {
	const folder = slug(p.profile.name) + '-portfolio';
	download(zipFiles(svelteKitFiles(p), folder), `${folder}-sveltekit.zip`, 'application/zip');
}
